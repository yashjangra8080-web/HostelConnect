import fs from 'fs';
import path from 'path';
import mysql from 'mysql2/promise';
import dotenv from 'dotenv';

dotenv.config({ path: path.resolve(process.cwd(), '.env') });
dotenv.config({ path: path.resolve(process.cwd(), 'server/.env') });

const dbConfig = {
  host: process.env.DB_HOST || '127.0.0.1',
  port: Number(process.env.DB_PORT) || 3306,
  user: process.env.DB_USER || 'root',
  password: process.env.DB_PASSWORD || 'yash',
  database: process.env.DB_NAME || 'hostelconnect',
};

// Tables to generate audit triggers for
const AUDITED_TABLES = [
  'students',
  'applications',
  'allotments',
  'rooms',
  'mess_config',
  'mess_refunds',
  'water_quality_reports',
  'complaints',
  'complaint_responses',
  'washing_machines',
  'notices',
  'maintenance_schedules'
];

async function generateAuditTriggers() {
  console.log('[Audit Trigger Generator] Connecting to MySQL...');
  const connection = await mysql.createConnection(dbConfig);

  try {
    const outputPath = path.resolve(process.cwd(), 'db/routines/audit_triggers.sql');
    const statements: string[] = [];

    statements.push('-- Auto-generated Audit Triggers for HostelConnect (reads @app_user_id)');
    statements.push('-- DO NOT EDIT MANUALLY. Generated by scripts/generate-audit-triggers.ts');

    for (const tableName of AUDITED_TABLES) {
      // 1. Get primary key column
      const [pkRows] = await connection.query<any[]>(`
        SELECT COLUMN_NAME 
        FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE 
        WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ? AND CONSTRAINT_NAME = 'PRIMARY'
      `, [dbConfig.database, tableName]);

      if (!pkRows || pkRows.length === 0) {
        console.warn(`[Audit Trigger Generator] Skipping ${tableName}: No primary key found.`);
        continue;
      }
      const pkCol = pkRows[0].COLUMN_NAME;

      // 2. Get all columns
      const [colRows] = await connection.query<any[]>(`
        SELECT COLUMN_NAME, DATA_TYPE 
        FROM INFORMATION_SCHEMA.COLUMNS 
        WHERE TABLE_SCHEMA = ? AND TABLE_NAME = ?
        ORDER BY ORDINAL_POSITION
      `, [dbConfig.database, tableName]);

      const cols = colRows.map((c) => c.COLUMN_NAME);

      const newJsonPairs = cols.map((c) => `'${c}', NEW.${c}`).join(', ');
      const oldJsonPairs = cols.map((c) => `'${c}', OLD.${c}`).join(', ');

      const insertTriggerName = `trg_audit_${tableName}_after_insert`;
      const updateTriggerName = `trg_audit_${tableName}_after_update`;
      const deleteTriggerName = `trg_audit_${tableName}_after_delete`;

      // AFTER INSERT Trigger
      statements.push(`DROP TRIGGER IF EXISTS ${insertTriggerName};`);
      statements.push(`CREATE TRIGGER ${insertTriggerName}
AFTER INSERT ON \`${tableName}\`
FOR EACH ROW
BEGIN
  INSERT INTO audit_log (actor_user_id, action, table_name, record_id, details, logged_at)
  VALUES (
    @app_user_id,
    'INSERT',
    '${tableName}',
    NEW.${pkCol},
    JSON_OBJECT(${newJsonPairs}),
    NOW()
  );
END;`);

      // AFTER UPDATE Trigger
      statements.push(`DROP TRIGGER IF EXISTS ${updateTriggerName};`);
      statements.push(`CREATE TRIGGER ${updateTriggerName}
AFTER UPDATE ON \`${tableName}\`
FOR EACH ROW
BEGIN
  INSERT INTO audit_log (actor_user_id, action, table_name, record_id, details, logged_at)
  VALUES (
    @app_user_id,
    'UPDATE',
    '${tableName}',
    NEW.${pkCol},
    JSON_OBJECT(
      'old', JSON_OBJECT(${oldJsonPairs}),
      'new', JSON_OBJECT(${newJsonPairs})
    ),
    NOW()
  );
END;`);

      // AFTER DELETE Trigger
      statements.push(`DROP TRIGGER IF EXISTS ${deleteTriggerName};`);
      statements.push(`CREATE TRIGGER ${deleteTriggerName}
AFTER DELETE ON \`${tableName}\`
FOR EACH ROW
BEGIN
  INSERT INTO audit_log (actor_user_id, action, table_name, record_id, details, logged_at)
  VALUES (
    @app_user_id,
    'DELETE',
    '${tableName}',
    OLD.${pkCol},
    JSON_OBJECT(${oldJsonPairs}),
    NOW()
  );
END;`);
    }

    const fileContent = statements.join('\n-- STATEMENT_BREAK\n') + '\n';
    fs.writeFileSync(outputPath, fileContent, 'utf8');
    console.log(`[Audit Trigger Generator] Successfully wrote ${AUDITED_TABLES.length * 3} audit triggers to ${outputPath}`);
  } finally {
    await connection.end();
  }
}

if (process.argv[1]?.includes('generate-audit-triggers')) {
  generateAuditTriggers().catch((err) => {
    console.error('[Audit Trigger Generator] Error:', err);
    process.exit(1);
  });
}

export { generateAuditTriggers };
